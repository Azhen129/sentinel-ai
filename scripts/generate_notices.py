"""Reproduce frontend notices from the npm lock and installed package licenses.

No network, installation, package scripts, or private runtime data are accessed.
Run after npm ci; --check verifies the committed static notice is current.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
from urllib.parse import quote


