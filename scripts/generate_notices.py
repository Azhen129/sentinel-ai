LICENSE_NAME = re.compile(r"^(?:licen[cs]e|copying|notice)(?:[._-].*)?$", re.IGNORECASE)


def create_notices(frontend: Path, installed_frontend: Path | None = None) -> str:
    frontend = Path(frontend).resolve()
    installed = Path(installed_frontend or frontend).resolve()
    lock = json.loads((frontend / "package-lock.json").read_text(encoding="utf-8"))
    if lock.get("lockfileVersion") != 3 or not isinstance(lock.get("packages"), dict):
        raise NoticeError("Expected npm lockfileVersion 3 with a packages tree")
    canonical = json.dumps(lock, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()
    entries = [(path, item) for path, item in lock["packages"].items() if path and not item.get("dev", False)]
    if not entries:
        raise NoticeError("No production dependency entries found")
    chunks = ["Sentinel AI frontend — third-party notices\n",
        "Scope: all npm lock entries not marked dev, including transitive dependencies and\n"
        "declaration/support packages. This conservative inventory is not a claim that every\n"
        "listed file is present in the tree-shaken JavaScript bundle. Build-only dependencies\n"
        "and backend dependencies are outside this frontend notice's scope. Their own licenses\n"
        "remain applicable to their distributions. The project MIT license does not replace\n"
        "the dependency licenses reproduced below. Vendored subdirectory texts are attributed\n"
        "to the containing package version; their separate versions are not inferred.\n",
        "Generated by: python scripts/generate_notices.py (after npm ci)\n"
        f"Canonical npm lock SHA-256: {hashlib.sha256(canonical).hexdigest()}\n"
        f"Production dependency entries: {len(entries)}\n"]
    for path, item in sorted(entries):
        relative = PurePosixPath(path)
        if (relative.is_absolute() or ".." in relative.parts or "\\" in path
                or not path.startswith("node_modules/") or item.get("link")):
            raise NoticeError("Unsupported local/link dependency path; review manually")
        directory = (installed / Path(*relative.parts)).resolve()
        if not directory.is_relative_to(installed / "node_modules"):
            raise NoticeError("Dependency directory leaves installed node_modules")
        expected_name = item.get("name") or path.rsplit("node_modules/", 1)[-1]
        try:
            package = json.loads((directory / "package.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            raise NoticeError(f"Missing installed manifest for {expected_name}; run npm ci") from None
        version = item.get("version")
        if package.get("name") != expected_name or package.get("version") != version:
            raise NoticeError(f"Installed package differs from lock: {expected_name}")
        if not isinstance(item.get("license"), str) or not item["license"]:
            raise NoticeError(f"Missing declared license: {expected_name}; review manually")
        resolved = item.get("resolved", "")
        if not resolved.startswith("https://registry.npmjs.org/"):
            raise NoticeError(f"Unexpected package origin: {expected_name}; review manually")
        chunks.append("\n" + "=" * 78 + "\n"
            f"Package: {expected_name}@{version}\n"
            f"Declared license: {item['license']}\n"
            f"Lock location: {path}\n"
            f"Package origin: {resolved}\n"
            f"Package page: https://www.npmjs.com/package/{quote(expected_name, safe='@/')}/v/{quote(version)}\n")
        licenses = []
        for source in sorted(directory.rglob("*"), key=lambda p: p.relative_to(directory).as_posix()):
            rel = source.relative_to(directory)
            if "node_modules" in rel.parts or not source.is_file() or not LICENSE_NAME.fullmatch(source.name):
                continue
            if not source.resolve().is_relative_to(directory):
                raise NoticeError(f"License path leaves package: {expected_name}")
            text = source.read_text(encoding="utf-8-sig").strip("\r\n")
            if not text.strip():
                raise NoticeError(f"Empty license text: {expected_name}")
            licenses.append((rel.as_posix(), text))
        if expected_name == "victory-vendor":
            if version != "36.9.2":
                raise NoticeError("Review the upstream victory-vendor license fallback for this new version")
            chunks.append("\nLicense source: reviewed matching upstream tag (root text omitted in npm package)\n"
                + VICTORY_LICENSE_URL + "\n\n" + VICTORY_LICENSE.rstrip() + "\n")
        elif not licenses:
            raise NoticeError(f"No packaged license text: {expected_name}; review manually")
        for rel, text in licenses:
            chunks.append(f"\nLicense source: {path}/{rel}\n\n{text}\n")
    return "\n".join(chunks).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--frontend", type=Path, default=Path(__file__).resolve().parents[1] / "frontend")
    parser.add_argument("--installed-frontend", type=Path, help="Optional existing frontend containing node_modules; files are read only")
    parser.add_argument("--check", action="store_true", help="Compare the committed notice without writing it")
    args = parser.parse_args()
    try:
        content = create_notices(args.frontend, args.installed_frontend)
        destination = args.frontend / "public" / "third-party-notices.txt"
        if args.check:
            if not destination.is_file() or destination.read_text(encoding="utf-8") != content:
                raise NoticeError("Frontend third-party notices are stale; regenerate after npm ci")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"Notice generation stopped: {exc if isinstance(exc, NoticeError) else type(exc).__name__}\n")
    print("Frontend third-party notices verified" if args.check else "Frontend third-party notices generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
